function windDirection(degrees) {
    var directions = ["北", "东北", "东", "东南", "南", "西南", "西", "西北"];
    return directions[Math.round(degrees / 45) % 8];
}

function windLevel(speed) {
    if (speed < 1) return 0;
    if (speed < 6) return 1;
    if (speed < 12) return 2;
    if (speed < 20) return 3;
    if (speed < 29) return 4;
    if (speed < 39) return 5;
    if (speed < 50) return 6;
    if (speed < 62) return 7;
    if (speed < 75) return 8;
    if (speed < 89) return 9;
    if (speed < 103) return 10;
    if (speed < 118) return 11;
    return 12;
}

function formatWeatherTime(value) {
    return value ? value.slice(11, 16) : "--:--";
}

function formatAirValue(value) {
    return value == null ? "暂无数据" : Math.round(value) + " μg/m³";
}

// 取当前天气现象的中文描述：站点实测优先（能表达「霾」这类 WMO 没有的现象）
function currentWeatherText(current) {
    return current.station_weather_text || weatherText(current.weather_code);
}

// 天气现象对应的图标。站点实测给的是中文，按关键字挑一个更贴合的表情，
// 挑不到就退回按 WMO 编码取。
function currentWeatherIcon(current) {
    var text = current.station_weather_text;
    if (text) {
        if (/霾|浮尘|扬沙|沙尘/.test(text)) return "😷";
        if (/雪/.test(text)) return "🌨️";
        if (/雨/.test(text)) return "🌧️";
        if (/雷/.test(text)) return "⛈️";
        if (/雾/.test(text)) return "🌫️";
        if (/阴/.test(text)) return "☁️";
        if (/多云/.test(text)) return "⛅";
        if (/晴/.test(text)) return "☀️";
    }
    return weatherIcon(current.weather_code);
}

